// bool/短路：&& 与 || 短路跳过右侧（x=0 时 100/x 若被求值则除零崩溃），
// 覆盖 !、true/false 字面量与优先级混排，期望退出码 35。
fn main() -> i32 {
    let x = 0;
    let a = (x != 0) && (100 / x);   // && 短路：x!=0 为假，跳过 100/x -> a=0
    let b = (x == 0) || (100 / x);   // || 短路：x==0 为真，跳过 100/x -> b=1
    let c = !(x == 0);               // !(真) -> 0
    let d = true;                    // 1
    let e = false;                   // 0
    let s = a + b + c + d + e;       // 0 + 1 + 0 + 1 + 0 = 2
    let f = (1 + 2 * 3 == 7) && false || true;   // (真 && 假 = 0) || 真 = 1
    s + f * 33                       // 2 + 33 = 35
}
